/// three.js Matrix4 with the same semantics: set() reads row-major,
/// multiply is the ordinary matrix product, applied to column vectors.
struct M4 {
    var m: [Double]   // row-major 16
    init(_ rows: [Double]) { m = rows }
    static func * (a: M4, b: M4) -> M4 {
        var r = [Double](repeating: 0, count: 16)
        for i in 0..<4 { for j in 0..<4 {
            var s = 0.0
            for k in 0..<4 { s += a.m[i * 4 + k] * b.m[k * 4 + j] }
            r[i * 4 + j] = s
        } }
        return M4(r)
    }
    var transposed: M4 {
        var r = [Double](repeating: 0, count: 16)
        for i in 0..<4 { for j in 0..<4 { r[j * 4 + i] = m[i * 4 + j] } }
        return M4(r)
    }
    func apply(_ v: [Double]) -> [Double] {
        (0..<4).map { i in m[i * 4] * v[0] + m[i * 4 + 1] * v[1] + m[i * 4 + 2] * v[2] + m[i * 4 + 3] * v[3] }
    }
}

